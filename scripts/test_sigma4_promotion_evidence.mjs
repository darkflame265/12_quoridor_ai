import assert from 'node:assert/strict';
import {wilson95,checkSigma4Promotion} from './sigma4-promotion-evidence.mjs';
const prior=checkSigma4Promotion({games:24,wins:15,uniqueGames:22,uniqueFirstSix:4,seedPairs:12,pairedRoles:true,modelsFrozen:true});
assert.equal(prior.eligible,false);assert.ok(prior.wilson95[0]<.5);
const conservative=checkSigma4Promotion({games:4,wins:3,uniqueGames:2,uniqueFirstSix:1,seedPairs:2,pairedRoles:true,modelsFrozen:true});
assert.equal(conservative.eligible,false);
assert.ok(conservative.blockingReasons.includes('enoughUniqueGames'));
const eligible=checkSigma4Promotion({games:100,wins:70,uniqueGames:95,uniqueFirstSix:12,seedPairs:50,pairedRoles:true,modelsFrozen:true});
assert.equal(eligible.eligible,true);
assert.throws(()=>wilson95(8,4));
console.log('PASS SIGMA4 evidence promotion gate: small sample and repeat games blocked');
