import {spawnSync} from 'node:child_process';
import {existsSync} from 'node:fs';
import {writeFile} from 'node:fs/promises';
import {homedir} from 'node:os';
import path from 'node:path';
import {mazeIdentity} from '../evaluation/maze-candidate-policy.mjs';
const local=path.join(homedir(),'.cargo','bin',process.platform==='win32'?'cargo.exe':'cargo');
const result=spawnSync(existsSync(local)?local:'cargo',['build','--locked','--release','--manifest-path','experimental-engine/Cargo.toml'],{stdio:'inherit',windowsHide:true});
if(result.status!==0)process.exit(result.status??1);
await writeFile('experimental-engine/target/release/source-manifest.json',JSON.stringify(mazeIdentity(),null,2)+'\n');
