import assert from 'node:assert/strict';
import {initial,moves,apply,legal} from '../src/engine.js';
import {tacticalLookahead,chooseLookaheadSigma4} from './sigma4-lookahead-choice.mjs';
const state=initial();
const choices=moves(state);
const root={pv:[choices[0]],diagnostics:{rootChildren:choices.slice(0,3).map((action,i)=>({action,visits:100-i*20,qFromRoot:0.5-i*.02}))}};
const a=chooseLookaheadSigma4(state,root,()=>.99,{depth:3,maxNodes:120});
assert.ok(legal(state,a.action));
assert.ok(a.lookaheadNodes>0&&a.lookaheadNodes<=120);
const repeat=chooseLookaheadSigma4(state,root,()=>.99,{depth:3,maxNodes:120});
assert.deepEqual(a.action,repeat.action);
const budget=chooseLookaheadSigma4(state,root,()=>.2,{depth:3,maxNodes:1});
assert.equal(budget.reason,'bounded-search-budget-exhausted');
assert.deepEqual(budget.action,choices[0]);
const winning={...initial(),p:[{x:4,y:1},{x:8,y:0}],turn:0};
const win=chooseLookaheadSigma4(winning,{pv:[{type:'move',x:3,y:1}],diagnostics:{rootChildren:[]}},()=>0);
assert.equal(win.reason,'forced-immediate-win');assert.deepEqual(win.action,{type:'move',x:4,y:0});
const s2={...initial(),p:[{x:4,y:5},{x:4,y:7}],turn:0};
const move={type:'move',x:4,y:4};
const block={type:'wall',x:4,y:7,o:'h'};
const escape=chooseLookaheadSigma4(s2,{pv:[move],diagnostics:{rootChildren:[{action:move,visits:100,qFromRoot:.3}]}},()=>0);
assert.equal(escape.reason,'exhaustive-immediate-loss-defense');assert.ok(legal(s2,escape.action));
assert.ok(moves(apply(s2,escape.action)).every(action=>apply(apply(s2,escape.action),action).winner===null));
console.log('PASS SIGMA4 minimax: bounded 3-ply search, deterministic replay, forced win, emergency block, no search budget overflow');
