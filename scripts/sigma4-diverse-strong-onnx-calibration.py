from __future__ import annotations
import json,math,hashlib,sys
from pathlib import Path
from collections import defaultdict
import numpy as np
import onnxruntime as ort

ROOT=Path(__file__).resolve().parent.parent
E=ROOT/'evaluation'
sys.path.insert(0,str(ROOT/'vendor/sigma-quoridor'))
from game import State,WallAction

def read(name):return json.loads((E/name).read_text(encoding='utf-8'))
bank=read('sigma4-diverse-strong-midgame-bank-20261106.json')
data=read('sigma4-diverse-strong-outcome-audit-20261106.json')
assert data['policyGames']==64 and data['analyzedIndependentSources']==16
basefile=ROOT/'vendor/sigma-quoridor/models/best.onnx'
newfile=E/'sigma4-value-residual-research-20261106.onnx'
base=ort.InferenceSession(str(basefile),providers=['CPUExecutionProvider'])
corrected=ort.InferenceSession(str(newfile),providers=['CPUExecutionProvider'])

def original_input(s):
 state=State(boardsize=9,depth=s['turn'],
             player1pos=(s['p'][0]['x'],8-s['p'][0]['y']),
             player2pos=(s['p'][1]['x'],8-s['p'][1]['y']),
             walls_p1=s['left'][0],walls_p2=s['left'][1],walls_initial=10)
 for wall in s['walls']:
  state._apply_wall(WallAction(wall['x'],7-wall['y'],wall['o']))
 state._recompute_dists()
 return state.to_nn_input()[None,...].astype(np.float32)
def infer(record):
 s=record['board']
 v=float(base.run(['value'],{'input':original_input(s)})[0][0,0])
 p=np.clip((v+1)/2,1e-6,1-1e-6)
 z=float(math.log(p/(1-p)))
 side=s['turn'];w=s['left']
 feature=np.asarray([[
   np.clip(z,-6,6)/4,np.clip(record['pathGap']/10,-2,2),
   (w[side]-w[1-side])/10,min(2,record['ply']/100),
   len(s['walls'])/20,(w[side]+w[1-side])/20]],dtype=np.float32)
 cv=float(corrected.run(['corrected_value'],{
  'features':feature,'original_logit':np.asarray([z],dtype=np.float32)})[0][0,0])
 return float(p),float((cv+1)/2)

out=[]
for pos in bank['positions'][:16]:
 o,c=infer(pos)
 item=next(x for x in data['byPosition'] if x['id']==pos['id'])
 assert item['positionId']==pos['positionId']
 results=[int(x['winningMover']) for x in item['policyResults']]
 assert len(results)==4
 def sq(p):return sum((p-y)**2 for y in results)/4
 out.append({'id':pos['id'],'split':pos['split'],'sourceStyle':pos['sourceStyle'],
  'wallCount':pos['wallCount'],'pathGap':pos['pathGap'],'ply':pos['ply'],
  'observedWins':sum(results),'observedWinFraction':sum(results)/4,
  'unanimous':sum(results) in (0,4),
  'originalPrediction':o,'correctedPrediction':c,'originalBrier':sq(o),'correctedBrier':sq(c),
  'originalAbsoluteError':abs(o-sum(results)/4),'correctedAbsoluteError':abs(c-sum(results)/4)})
def summarize(rows):
 if not rows:return None
 avg=lambda key:sum(r[key] for r in rows)/len(rows)
 return {'uniquePositions':len(rows),'continuations':4*len(rows),
  'meanObservedWinRate':avg('observedWinFraction'),
  'originalBrier':avg('originalBrier'),'correctedBrier':avg('correctedBrier'),
  'originalMeanAbsoluteError':avg('originalAbsoluteError'),
  'correctedMeanAbsoluteError':avg('correctedAbsoluteError'),
  'correctedBetterPositions':sum(r['correctedBrier']<r['originalBrier'] for r in rows),
  'ambiguousPositions':sum(not r['unanimous'] for r in rows)}
byStyle={style:summarize([r for r in out if r['sourceStyle']==style]) for style in bank['settings']['sourcePolicies']}
report={'version':'sigma4-diverse-midgame-frozen-onnx-calibration-v1',
 'modelHashOriginal':hashlib.sha256(basefile.read_bytes()).hexdigest(),
 'modelHashCorrected':hashlib.sha256(newfile.read_bytes()).hexdigest(),
 'positionSplitsPreassigned':True,'fitOrEpochSelectionUsedTheseData':False,
 'all':summarize(out),'development':summarize([r for r in out if r['split']=='development']),
 'holdout':summarize([r for r in out if r['split']=='holdout']),
 'bySourceStyle':byStyle,
 'positions':out,
 'limitations':['Four outcomes per board are correlated, not four independent training labels',
 'Source boards are generated by MCTS variants sharing same base ONNX',
 'Outcome labels depend on candidate and opponent policy, not solved minimax truth',
 '16 source boards insufficient to infer statistically reliable playing strength'],
 'promotionApproved':False}
(E/'sigma4-diverse-strong-onnx-calibration-20261106.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
print('DIVERSE MIDGAME CALIBRATION',json.dumps({k:report[k] for k in ('all','development','holdout','bySourceStyle')},indent=2))
