import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {clone,initial,legal,apply,moves} from '../src/engine.js';
import {confidenceGate} from './sigma3-override-confidence-gate.mjs';
const start=initial();
const first=moves(start)[0];
const initialCopy=JSON.stringify(start);
const opening=confidenceGate(start,{pv:[first]},{absolutePly:0});
assert.equal(opening.changed,false);
assert.equal(opening.reason,'opening-18-protected');
assert.deepEqual(opening.action,first);
assert.equal(JSON.stringify(start),initialCopy);
const fixtures=JSON.parse(readFileSync('evaluation/sigma3-unseen-middle-audited.json','utf8'));
const fixture=fixtures.find(x=>x.id===103);
const s=clone(fixture.s);
const before=JSON.stringify(s);
const ranked=fixture.rootCandidates.map((x,i)=>({action:x.action,visits:130-i*10,qFromRoot:.1-i*.015}));
const search={pv:[fixture.rootCandidates[0].action],diagnostics:{rootChildren:ranked}};
const result=confidenceGate(s,search,{absolutePly:30,maxQGap:.15,maxQPenalty:.10,minimumVisits:15,minimumTacticalGain:.8,attackBeam:6,defenderBeam:4,wallRiskWeight:.35});
assert.ok(legal(s,result.action));
assert.equal(typeof result.changed,'boolean');
assert.equal(JSON.stringify(s),before);
if(result.changed)assert.equal(result.reason,'confidence-approved');
console.log('PASS confidence gate: opening protection, legal action, preserved root, valid override result',result.reason);
