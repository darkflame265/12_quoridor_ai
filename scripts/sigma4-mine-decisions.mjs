import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {apply,legal,distance,notation} from '../src/engine.js';
const hash=o=>createHash('sha256').update(JSON.stringify(o)).digest('hex');
const report=JSON.parse(readFileSync('evaluation/sigma4-research-games.json','utf8'));
const groups={train:[4187,6721],holdout:[9413,12011]};
const out={version:'sigma4-divergence-mining-v1',source:'evaluation/sigma4-research-games.json',groups,complete:report.games.length===8,uniqueGames:new Set(report.games.map(g=>g.sequenceHash)).size,
 decisions:[],candidateBranches:[],warnings:[]};
const seen=new Set();
for(const game of report.games){
 for(const t of game.trace){
  if(t.variant!=='sigma3'||!legal(t.state,t.action))continue;
  const key=hash([t.state.p,t.state.walls,t.state.left,t.state.turn]);
  if(seen.has(key))continue;
  seen.add(key);
  const usable=t.rootCandidates.filter(c=>c.action&&legal(t.state,c.action)&&c.visits>=5&&Number.isFinite(c.qFromRoot));
  if(usable.length<2)continue;
  const primary=usable[0],base=t.action,baseStats=usable.find(c=>JSON.stringify(c.action)===JSON.stringify(base));
  const alternatives=usable.filter(c=>JSON.stringify(c.action)!==JSON.stringify(base)&&primary.qFromRoot-c.qFromRoot<=0.18).slice(0,2);
  const before=[distance(t.state,0),distance(t.state,1)];
  const after=apply(t.state,base), afterD=[distance(after,0),distance(after,1)];
  const gap=alternatives.length?(primary.qFromRoot-alternatives[0].qFromRoot):null;
  const label=game.sigma3Won?1:0;
  const split=groups.train.includes(game.seed)?'train':'holdout';
  const record={id:'s'+game.seed+'-'+game.sigma3Side+'-p'+t.ply,split,seed:game.seed,side:t.side,
   openingHash:game.openingHash,gameSequenceHash:game.sequenceHash,rootKey:key,ply:t.ply,
   won:label,chosen:base,chosenNotation:notation(base),mctsLeader:primary.action,
   disagreement:t.disagreement,leaderVisits:primary.visits,chosenVisits:baseStats?.visits??0,
   rootTop:usable.slice(0,4),alternativeCount:alternatives.length,
   before,after:afterD,wallCounts:t.state.left};
  out.decisions.push(record);
  if(!game.sigma3Won&&alternatives.length){
   out.candidateBranches.push({...record,rootState:t.state,
    forcedActions:[base,alternatives[0].action],
    alternatives:alternatives.map(c=>({action:c.action,notation:notation(c.action),visits:c.visits,qFromRoot:c.qFromRoot})),
    priority:(t.disagreement?2:0)+(gap!==null&&gap<.04?2:0)+(primary.visits>=20?1:0)});
  }
 }
}
out.candidateBranches.sort((a,b)=>b.priority-a.priority||a.ply-b.ply);
out.summary={games:report.games.length,distinctStartFamilies:new Set(report.games.map(g=>g.openingHash)).size,
 uniqueCompleteSequences:new Set(report.games.map(g=>g.sequenceHash)).size,
 sigma3Wins:report.games.filter(g=>g.sigma3Won).length,
 sigma3Losses:report.games.filter(g=>!g.sigma3Won&&!g.cutoff).length,
 firstWins:report.games.filter(g=>g.sigma3Side===0&&g.sigma3Won).length,
 secondWins:report.games.filter(g=>g.sigma3Side===1&&g.sigma3Won).length,
 nonduplicatedDecisionStates:out.decisions.length,lossBranchCandidates:out.candidateBranches.length,
 holdoutSeedsNeverUsedForTraining:groups.holdout.every(seed=>!groups.train.includes(seed))};
out.warnings=['Game outcomes label overall game trajectories, not proven individual move quality',
 'Counterfactual candidates must be tested against strong opponent responses',
 'Small 4-opening dataset is a pipeline smoke test, not evidence of SIGMA4 superiority',
 'Controlled opening plies are not generated by the agents'];
writeFileSync('evaluation/sigma4-research-mined.json',JSON.stringify(out,null,2));
console.log('MINED',JSON.stringify(out.summary));
console.log('TOP',out.candidateBranches.slice(0,8).map(({id,priority,ply,chosenNotation,alternatives})=>({id,priority,ply,chosenNotation,alternatives:alternatives.map(x=>x.notation)})));
