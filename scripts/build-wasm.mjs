import {spawnSync} from 'node:child_process';
import {mkdir,readFile,writeFile,copyFile} from 'node:fs/promises';
import {existsSync} from 'node:fs';
import {homedir} from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
const local=path.join(homedir(),'.cargo','bin',process.platform==='win32'?'cargo.exe':'cargo'),cargo=existsSync(local)?local:'cargo';
const result=spawnSync(cargo,['build','--manifest-path','rust-engine/Cargo.toml','--release','--lib','--target','wasm32-unknown-unknown'],{stdio:'inherit'});if(result.status!==0)process.exit(result.status??1);
await mkdir('public',{recursive:true});await copyFile('rust-engine/target/wasm32-unknown-unknown/release/quoridor_atlas.wasm','public/atlas.wasm');
const hash=b=>createHash('sha256').update(b).digest('hex'),files=['rust-engine/src/lib.rs','rust-engine/Cargo.toml','rust-engine/Cargo.lock','rust-toolchain.toml'];
const sources={};for(const f of files)sources[f]=hash(await readFile(f));await writeFile('public/atlas-wasm.json',JSON.stringify({abi:1,artifact:hash(await readFile('public/atlas.wasm')),sources},null,2)+'\n');console.log('WASM artifact and source checksums saved.');
