import assert from 'node:assert/strict';
import {initial,apply,legal,moves,clone} from '../src/engine.js';
import {opponentForcedPawnGoalInTwo,chooseVerifiedTwoTurnV8} from './sigma4-verified-two-turn-v8.mjs';
const far=initial();
const action=moves(far)[0];
assert.equal(opponentForcedPawnGoalInTwo(far,action).reason,'opponent-too-far');
const near={p:[{x:4,y:6},{x:0,y:6}],walls:[],left:[0,0],turn:0,winner:null};
const loss={type:'move',x:4,y:5};
assert(legal(near,loss));
const audit=opponentForcedPawnGoalInTwo(near,loss);
assert.equal(audit.forced,true);
assert.equal(audit.reason,'unblockable-two-turn-pawn-goal');
assert(audit.searched>0);
const search={pv:[loss],diagnostics:{rootChildren:[{action:loss,visits:200,qFromRoot:0.1}]}};
const picked=chooseVerifiedTwoTurnV8(near,search,()=>.99);
assert(legal(near,picked.action));
assert(['no-proven-escape','escaped'].includes(picked.proofGate));
const goal={p:[{x:4,y:1},{x:0,y:6}],walls:[],left:[0,0],turn:0,winner:null};
const own={type:'move',x:4,y:0};
const win=chooseVerifiedTwoTurnV8(goal,{pv:[{type:'move',x:4,y:2}],diagnostics:{rootChildren:[]}},()=>.99);
assert.deepEqual(win.action,own);
assert.equal(win.reason,'immediate-own-win');
console.log('PASS V8 two-turn tactical proofs',JSON.stringify({threat:audit,picked:picked.proofGate,won:win.action}));
