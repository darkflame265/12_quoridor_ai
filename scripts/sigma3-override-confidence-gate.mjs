import {apply,distance,legal} from '../src/engine.js';
import {directWallThreat} from './sigma3-wall-threat-probe.mjs';
import {conservativeTacticalChoice} from './sigma3-strong-advance-guard.mjs';
export function confidenceGate(state,search,opts={}) {
 const base=search.pv?.[0], turn=state.turn, foe=1-turn;
 if(!base||!legal(state,base)) throw Error('illegal baseline');
 const rootPly=opts.absolutePly??0;
 if(rootPly<18)return {action:base,changed:false,reason:'opening-18-protected',elapsedMs:0};
 const tactical=conservativeTacticalChoice(state,search,opts);
 if(!tactical.changed)return tactical;
 const candidate=tactical.action, baseline=apply(state,base), alternative=apply(state,candidate);
 const dBase=[distance(baseline,turn),distance(baseline,foe)];
 const dAlt=[distance(alternative,turn),distance(alternative,foe)];
 const ownPenalty=dAlt[0]-dBase[0],foePenalty=dBase[1]-dAlt[1];
 const wallDelta=(alternative.left[turn]-alternative.left[foe])-(baseline.left[turn]-baseline.left[foe]);
 const materialMargin=-ownPenalty-foePenalty+.65*wallDelta;
 const ranked=search.diagnostics?.rootChildren||[];
 const q0=ranked.find(x=>JSON.stringify(x.action)===JSON.stringify(base))?.qFromRoot??null;
 const q1=ranked.find(x=>JSON.stringify(x.action)===JSON.stringify(candidate))?.qFromRoot??null;
 const qPenalty=q0!==null&&q1!==null?q0-q1:null;
 const reasons=[];
 if(qPenalty===null||qPenalty>.065)reasons.push('mcts-q-confidence');
 if(tactical.tacticalImprovement<1.45)reasons.push('weak-tactical-gain');
 if(materialMargin<-.7)reasons.push('material-and-path-regression');
 if(ownPenalty>=2)reasons.push('own-path-regression');
 if(base.type==='wall'&&candidate.type==='move'&&foePenalty>=1)reasons.push('lost-opponent-detour');
 if(base.type==='move'&&candidate.type==='wall'&&ownPenalty>=1)reasons.push('lost-pawn-tempo');
 const riskBase=directWallThreat(baseline,turn,{topK:1}).maxNetDamage;
 const riskAlt=directWallThreat(alternative,turn,{topK:1}).maxNetDamage;
 if(riskAlt>riskBase+1)reasons.push('opponent-wall-threat');
 return {action:reasons.length?base:candidate,changed:reasons.length===0,reason:reasons.length?reasons.join(','):'confidence-approved',elapsedMs:tactical.elapsedMs,confidence:{ownPenalty,foePenalty,wallDelta,materialMargin,qPenalty,tacticalGain:tactical.tacticalImprovement,riskBase,riskAlt}};
}
